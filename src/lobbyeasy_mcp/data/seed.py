"""Render `fixtures.build_dataset()` as SQL (`sql/seed.sql`).

Run `uv run python -m lobbyeasy_mcp.data.seed > sql/seed.sql` after editing the
fixtures; `tests/test_seed.py` fails if the committed file is stale.
"""

from __future__ import annotations

from datetime import datetime
from uuid import UUID

from lobbyeasy_mcp.fixtures import build_dataset


def _lit(value: object) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, datetime):
        return f"'{value.isoformat()}'"
    if isinstance(value, list):
        return "ARRAY[" + ", ".join(_lit(v) for v in value) + "]::int[]"
    if isinstance(value, UUID):
        return f"'{value}'"
    return "'" + str(value).replace("'", "''") + "'"


def _insert(table: str, columns: list[str], rows: list[list[object]]) -> str:
    values = ",\n".join("  (" + ", ".join(_lit(v) for v in row) + ")" for row in rows)
    return f"INSERT INTO {table} ({', '.join(columns)}) VALUES\n{values};\n"


